import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';

const root = process.cwd();
const require = createRequire(import.meta.url);
const packageJson = JSON.parse(
  await readFile(resolve(root, 'package.json'), 'utf8'),
);
const dependencies = {
  ...packageJson.dependencies,
  ...packageJson.optionalDependencies,
};
const candidates = Object.keys(dependencies)
  .filter((name) => name.startsWith('@wasnaker/module-'))
  .sort();

const apiModules = [];
for (const packageName of candidates) {
  try {
    require.resolve(`${packageName}/api/manifest`);
    apiModules.push({
      packageName,
      hasEntities: canResolve(`${packageName}/api/entities`),
      hasMigrations: canResolve(`${packageName}/api/migrations`),
    });
  } catch {
    // A package without an API manifest is a web-only module and is skipped.
  }
}

function canResolve(specifier) {
  try {
    require.resolve(specifier);
    return true;
  } catch {
    return false;
  }
}

const imports = apiModules.flatMap(({ packageName, hasEntities, hasMigrations }, index) => [
  `import { moduleManifest as moduleManifest${index} } from '${packageName}/api/manifest';`,
  ...(hasEntities
    ? [`import { moduleEntities as moduleEntities${index} } from '${packageName}/api/entities';`]
    : []),
  ...(hasMigrations
    ? [`import { moduleMigrations as moduleMigrations${index} } from '${packageName}/api/migrations';`]
    : []),
]);
const manifests = apiModules.map((_, index) => `moduleManifest${index}`);
const entities = apiModules.flatMap(({ hasEntities }, index) =>
  hasEntities ? [`...moduleEntities${index}`] : [],
);
const migrations = apiModules.flatMap(({ hasMigrations }, index) =>
  hasMigrations ? [`...moduleMigrations${index}`] : [],
);
const source = [
  '/** Generated by scripts/generate-backend-module-registry.mjs. Do not edit. */',
  ...imports,
  '',
  `export const BACKEND_MODULE_MANIFESTS = [${manifests.join(', ')}] as const;`,
  `export const BACKEND_MODULE_ENTITIES = [${entities.join(', ')}] as const;`,
  `export const BACKEND_MODULE_MIGRATIONS = [${migrations.join(', ')}] as const;`,
  '',
].join('\n');

const output = resolve(root, 'src/module-runtime/module-manifest.registry.ts');
await mkdir(dirname(output), { recursive: true });
let previous = '';
try {
  previous = await readFile(output, 'utf8');
} catch {
  // First generation.
}
if (previous !== source) {
  await writeFile(output, source, 'utf8');
}
console.log(
  `Registered ${apiModules.length} API module(s), ${entities.length} entity set(s), and ${migrations.length} migration set(s).`,
);
